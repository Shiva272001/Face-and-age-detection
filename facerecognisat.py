# STEP 7 — Face Recognition from captured photo
# ─────────────────────────────────────────────
def recognize_face(img_path: str) -> dict | None:
    """
    Returns profile dict if face matched in history,
    or a 'Unknown Guest' profile if not matched,
    or None if no face detected at all.
    """
    img         = face_recognition.load_image_file(img_path)
    locations   = face_recognition.face_locations(img)
    encodings   = face_recognition.face_encodings(img, locations)

    if not encodings:
        print("😶  No face detected in the photo. Try again.")
        return None

    print(f"👤  {len(encodings)} face(s) detected.")

    for enc in encodings:
        if known_encodings:
            distances = face_recognition.face_distance(known_encodings, enc)
            best_idx  = int(np.argmin(distances))
            best_dist = distances[best_idx]

            # Threshold: lower = stricter. 0.5 is a good balance.
            if best_dist < 0.5:
                profile = known_profiles[best_idx]
                print(f"✅  Matched: {profile['name']} (distance: {best_dist:.3f})")
                return profile
            else:
                print(f"🔍  No close match found (closest dist: {best_dist:.3f})")

    # Return guest profile for unrecognized faces
    return {
        "name": "Guest",
        "age": "Unknown",
        "job": "Unknown",
        "department": "Unknown"
    }

